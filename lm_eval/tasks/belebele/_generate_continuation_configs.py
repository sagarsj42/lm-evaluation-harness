"""Generate the continuation-format Belebele task tree.

The letter-format tasks lay the four options out as an A-D list and score the letters,
which a base model cannot do. These variants score the option text instead, following
`mmlu/continuation`.

The language list is read back from the letter-format configs on disk rather than from
the datasets-server API, so the two trees cannot drift apart and the generator stays
runnable offline.

Usage: python _generate_continuation_configs.py [--check]
"""

import pathlib
import sys

import yaml


ROOT = pathlib.Path(__file__).parent
SRC = ROOT / "default"
OUT = ROOT / "continuation"
GROUP = OUT / "_belebele_continuation.yaml"
TEMPLATE_NAME = "_continuation_template_yaml"

# Only doc_to_text/doc_to_choice/metric_list differ from ../default/_default_template_yaml.
# `fewshot_split: test` is carried over deliberately: Belebele ships a test split and
# nothing else, and pointing fewshot_split at it is what makes lm-eval exclude the eval
# doc from its own shots. The dataset is intended for 0-shot use here.
TEMPLATE = """\
# Generated by _generate_continuation_configs.py
dataset_path: facebook/belebele
fewshot_config:
  sampler: first_n
output_type: multiple_choice
should_decontaminate: true
doc_to_decontamination_query: "{{question}}"
doc_to_text: "P: {{flores_passage}}\\nQ: {{question.strip()}}\\nAnswer:"
doc_to_choice: "{{[mc_answer1, mc_answer2, mc_answer3, mc_answer4]}}"
doc_to_target: "{{['1', '2', '3', '4'].index(correct_answer_num)}}"
metric_list:
  - metric: acc
    aggregation: mean
    higher_is_better: true
  - metric: acc_norm
    aggregation: mean
    higher_is_better: true
  - metric: acc_bytes
    aggregation: mean
    higher_is_better: true
metadata:
  version: 0.0
"""

LEAF = """\
# Generated by _generate_continuation_configs.py
dataset_name: {variant}
fewshot_split: test
include: {template}
task: belebele_{variant}_continuation
test_split: test
"""


def variants():
    """Read the language variants from the letter-format leaf configs."""
    found = []
    for path in sorted(SRC.glob("belebele_*.yaml")):
        cfg = yaml.safe_load(path.read_text())
        found.append(cfg["dataset_name"])
    if not found:
        raise SystemExit(f"no letter-format belebele_*.yaml configs found in {SRC}")
    return sorted(found)


class IndentedDumper(yaml.SafeDumper):
    """Indent sequences under their key, matching the hand-written configs."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def group_yaml(names):
    aggregate = [
        {"metric": metric, "aggregation": "mean", "weight_by_size": True}
        for metric in ("acc", "acc_norm", "acc_bytes")
    ]
    body = yaml.dump(
        {
            "group": "belebele_continuation",
            "group_alias": "belebele (continuation)",
            "task": [f"belebele_{name}_continuation" for name in names],
            "aggregate_metric_list": aggregate,
            "metadata": {"version": 0.0},
        },
        Dumper=IndentedDumper,
        sort_keys=False,
        width=float("inf"),
        allow_unicode=True,
    )
    return "# Generated by _generate_continuation_configs.py\n" + body


def build():
    names = variants()
    files = {
        OUT / TEMPLATE_NAME: TEMPLATE,
        GROUP: group_yaml(names),
    }
    for name in names:
        files[OUT / f"belebele_{name}.yaml"] = LEAF.format(
            variant=name, template=TEMPLATE_NAME
        )
    return files


def main():
    check = "--check" in sys.argv[1:]
    files = build()
    stale = []
    for path, text in files.items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
            continue
        path.parent.mkdir(exist_ok=True)
        path.write_text(text)
    extra = sorted(
        p.name for p in OUT.glob("*") if OUT.exists() and p not in files and p.is_file()
    )
    if check:
        if stale or extra:
            raise SystemExit(
                f"continuation configs are out of date: {len(stale)} stale "
                f"{stale[:5]}, {len(extra)} unexpected {extra[:5]}"
            )
        print(f"up to date: {len(files)} files, {len(variants())} variants")
    else:
        print(f"wrote {len(files)} files for {len(variants())} variants to {OUT}")
        if extra:
            print(f"warning: {len(extra)} unexpected files left in place: {extra[:5]}")


if __name__ == "__main__":
    main()
