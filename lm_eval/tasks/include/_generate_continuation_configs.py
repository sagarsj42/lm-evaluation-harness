"""Generate the continuation-format INCLUDE task trees.

The letter-format tasks lay the four options out as an A-D list and score the letters,
which a base model cannot do. These variants score the option text instead, following
`mmlu/continuation`.

Each tree mirrors its letter-format source, so the per-language domain lists are read
back from that source rather than restated here.

Usage: python _generate_continuation_configs.py [--check]
"""

import pathlib
import sys

import yaml


ROOT = pathlib.Path(__file__).parent

VARIANTS = {
    "default_continuation": {
        "source": "default",
        "infix": "",
        "fewshot": False,
    },
    "few_shot_en_continuation": {
        "source": "few_shot_en",
        "infix": "few_shot_en_",
        "fewshot": True,
    },
}

TEMPLATE = """\
# Generated by _generate_continuation_configs.py
{header}dataset_path: CohereForAI/include-base-44
dataset_name: {language}
test_split: test
{fewshot}output_type: multiple_choice
doc_to_text: "Question: {{{{question.strip()}}}}\\nAnswer:"
doc_to_choice: "{{{{[option_a, option_b, option_c, option_d]}}}}"
doc_to_target: answer
metric_list:
  - metric: acc
    aggregation: mean
    higher_is_better: true
  - metric: acc_norm
    aggregation: mean
    higher_is_better: true
  - metric: acc_bytes
    aggregation: mean
    higher_is_better: true
metadata:
  version: 0.0
"""

FEWSHOT_BLOCK = """\
fewshot_split: validation
fewshot_config:
  process_docs: null
  sampler: !function utils.DomainMatchedSampler
"""

# Kept identical to the letter-format variants' utils.py, which each define their own
# process functions; the fewshot variant additionally pulls in the shared sampler.
UTILS = """\
from functools import partial
{shared}

CATEGORIES = [
    "Applied Science",
    "Arts & Humanities",
    "Business & Commerce",
    "Driving License",
    "General knowledge",
    "Health oriented education",
    "Marine License",
    "Medical License",
    "Professional certification",
    "STEM",
    "Social Science",
]


def process_docs(dataset, category):
    return dataset.filter(lambda x: x["domain"] == category)


process_functions = {{
    f"process_{{category.lower().replace(' & ', '_').replace(' ', '_')}}": partial(
        process_docs, category=category
    )
    for category in CATEGORIES
}}

globals().update(process_functions)
"""

SHARED_BLOCK = """
from lm_eval.tasks.include import common


IncludeTask = common.IncludeTask
DomainMatchedSampler = common.DomainMatchedSampler
"""


def domains_of(language):
    """Read a language's domain list back from its letter-format group configs.

    Both letter-format variants are cross-checked, so a drift between them surfaces
    here instead of silently producing two continuation trees that disagree.
    """
    slug = language.lower().replace(" ", "_")
    listings = {}
    for source, infix in (("default", ""), ("few_shot_en", "few_shot_en_")):
        group = ROOT / source / language / f"_include_base_44_{slug}.yaml"
        tasks = yaml.safe_load(group.read_text())["task"]
        prefix = f"include_base_44_{slug}_{infix}"
        listings[source] = [task[len(prefix) :] for task in tasks]
    if set(listings["default"]) != set(listings["few_shot_en"]):
        raise ValueError(f"{language}: letter-format variants list different domains")
    return listings["default"]


def generate(check=False):
    written = []
    for variant, spec in VARIANTS.items():
        source, infix, fewshot = spec["source"], spec["infix"], spec["fewshot"]
        for language_dir in sorted((ROOT / source).iterdir()):
            if not language_dir.is_dir() or language_dir.name.startswith("__"):
                continue
            language = language_dir.name
            slug = language.lower().replace(" ", "_")
            out = ROOT / variant / language
            template_name = f"_{slug}_{infix}continuation_template_yaml"

            files = {
                template_name: TEMPLATE.format(
                    language=language,
                    header="class: !function utils.IncludeTask\n" if fewshot else "",
                    fewshot=FEWSHOT_BLOCK if fewshot else "",
                )
            }

            domains = domains_of(language)
            files["utils.py"] = UTILS.format(shared=SHARED_BLOCK if fewshot else "")

            for domain in domains:
                files[f"include_base_44_{slug}_{infix}{domain}_continuation.yaml"] = (
                    "# Generated by _generate_continuation_configs.py\n"
                    f"include: {template_name}\n"
                    f"process_docs: !function utils.process_{domain}\n"
                    f"task: include_base_44_{slug}_{infix}{domain}_continuation\n"
                )

            leaves = "\n".join(
                f"  - include_base_44_{slug}_{infix}{d}_continuation" for d in domains
            )
            files[f"_include_base_44_{slug}_{infix}continuation.yaml"] = (
                "# Generated by _generate_continuation_configs.py\n"
                f"group: include_base_44_{slug}_{infix}continuation\n"
                f"task:\n{leaves}\n"
                "aggregate_metric_list:\n"
                "  - metric: acc\n    weight_by_size: true\n"
                "  - metric: acc_norm\n    weight_by_size: true\n"
                "  - metric: acc_bytes\n    weight_by_size: true\n"
                "metadata:\n  version: 0.0\n"
            )

            for name, body in files.items():
                path = out / name
                if check:
                    if not path.exists() or path.read_text() != body:
                        written.append(path)
                    continue
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(body)
                written.append(path)
    return written


if __name__ == "__main__":
    stale = generate(check="--check" in sys.argv)
    if "--check" in sys.argv:
        print(f"stale or missing files: {len(stale)}")
        sys.exit(1 if stale else 0)
    print(f"files written: {len(stale)}")
